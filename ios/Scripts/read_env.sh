#!/bin/bash

# Script to read .env file and export as environment variables for Xcode
# This script is called during the build process

# Get the project root (2 levels up from ios/Scripts)
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

# Determine which .env file to use
# Priority: 1) Command line argument, 2) CONFIGURATION variable, 3) default
if [ $# -gt 0 ] && [ -f "${PROJECT_ROOT}/$1" ]; then
    ENV_FILE="${PROJECT_ROOT}/$1"
elif [ "${CONFIGURATION}" == "Debug-development" ] || [ "${CONFIGURATION}" == "Release-development" ] || [ "${CONFIGURATION}" == "Profile-development" ]; then
    ENV_FILE="${PROJECT_ROOT}/.env.development"
elif [ "${CONFIGURATION}" == "Debug-staging" ] || [ "${CONFIGURATION}" == "Release-staging" ] || [ "${CONFIGURATION}" == "Profile-staging" ]; then
    ENV_FILE="${PROJECT_ROOT}/.env.staging"
elif [ "${CONFIGURATION}" == "Debug-production" ] || [ "${CONFIGURATION}" == "Release-production" ] || [ "${CONFIGURATION}" == "Profile-production" ] || [ "${CONFIGURATION}" == "Release" ] || [ "${CONFIGURATION}" == "Debug" ]; then
    ENV_FILE="${PROJECT_ROOT}/.env.production"
else
    ENV_FILE="${PROJECT_ROOT}/.env.development"
fi

if [ ! -f "$ENV_FILE" ]; then
    echo "Warning: $ENV_FILE not found, using default .env.development"
    ENV_FILE="${PROJECT_ROOT}/.env.development"
fi

echo "Reading environment from: $ENV_FILE"

# Read the .env file and create a Swift file with the constants
OUTPUT_FILE="${PROJECT_ROOT}/ios/Runner/EnvConfig.swift"

# Start the Swift file
cat > "$OUTPUT_FILE" << EOF
// This file is auto-generated by Scripts/read_env.sh
// Do not edit manually - changes will be overwritten

import Foundation

struct EnvConfig {
EOF

# Read each line from .env file
while IFS= read -r line; do
    # Skip comments and empty lines
    if [[ $line =~ ^#.*$ ]] || [ -z "$line" ]; then
      continue
    fi
    
    # Only process lines with = sign
    if [[ $line =~ = ]]; then
        key=$(echo "$line" | cut -d'=' -f1 | xargs)
        value=$(echo "$line" | cut -d'=' -f2- | xargs | sed 's/^"//' | sed 's/"$//' | sed "s/^'//" | sed "s/'$//")
        
        # Convert key to Swift-friendly format (uppercase with underscores)
        swift_key=$(echo "$key" | tr '[:lower:]' '[:upper:]' | tr '-' '_')
        
        # Export for use in this script
        export "$key=$value"
        
        # Add to Swift file
        echo "    static let $swift_key = \"$value\"" >> "$OUTPUT_FILE"
        echo "Found env key: $key = $value"
    fi
done < "$ENV_FILE"

# Close the Swift struct
cat >> "$OUTPUT_FILE" << EOF
}
EOF

echo "Generated $OUTPUT_FILE"

